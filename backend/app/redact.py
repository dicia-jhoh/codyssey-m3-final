"""개인정보 가림 — 화면·공유 링크에 나가기 전에 반드시 거친다(AI 윤리 요건).

사진은 가리기 전에 비전 LLM 으로 간다. extract 단계가 글자로 바꾼 뒤 이 함수를
지나야 RAG·화면·공유 단계로 간다.
"""

import re

# \b(단어 경계)는 안 쓴다 — Python 정규식에서 한글은 \w로 취급돼서, 숫자 바로 뒤에
# 조사가 붙으면(예: "900101-1234567이며") 숫자↔한글 사이에 경계가 안 생겨 \b가
# 매칭을 놓친다. 대신 숫자가 더 이어지지 않는지만 보는 (?<!\d)/(?!\d)를 쓴다 —
# 의도(이 숫자 뭉치가 더 큰 숫자의 일부가 아님)는 그대로 지키면서 한글 조사가
# 바로 붙어도 잡는다.

# 주민등록번호: 6자리-7자리. 뒷자리 첫 숫자는 1~4(내국인)·5~8(외국인)
_RRN = re.compile(r"(?<!\d)(\d{6})[-\s]?([1-8])\d{6}(?!\d)")
# 계좌번호 후보: 숫자 묶음이 하이픈으로 3~4덩어리(카카오뱅크 3333-01-1234567 처럼 7자리 묶음 포함), 또는 숫자만 10~14자리
_ACCOUNT = re.compile(r"(?<!\d)\d{2,7}(?:-\d{2,7}){2,3}(?!\d)|(?<!\d)\d{10,14}(?!\d)")


def _hide_account(m: re.Match) -> str:
    # 날짜(2026-10-31, 숫자 8개)는 모양이 같아서 숫자 개수로 가른다 — 계좌는 10자리 이상이다
    digits = sum(c.isdigit() for c in m.group(0))
    return "[계좌번호 가림]" if digits >= 10 else m.group(0)


# 전화번호: 0 으로 시작하는 지역·휴대폰 번호 - 3~4자리 - 4자리. 계좌번호와 모양이 비슷해서
# 계좌보다 먼저 가린다 — 안 그러면 「[계좌번호 가림]」으로 잘못 적힌다
_PHONE = re.compile(r"(?<![\d-])0\d{1,2}-\d{3,4}-\d{4}(?![\d-])")


def redact(text: str) -> str:
    """주민번호는 앞 6자리와 성별 숫자만 남기고, 전화번호·계좌번호는 통째로 가린다."""
    text = _RRN.sub(lambda m: f"{m.group(1)}-{m.group(2)}******", text)
    text = _PHONE.sub("[전화번호 가림]", text)
    return _ACCOUNT.sub(_hide_account, text)
